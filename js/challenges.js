//   ・少数意見は採用でも多数決で消してよいものでもない
//   ・参加を発言・代表・司会・完成物の出来だけで判断しない
//   ・行事の成功と子どもの学びを同一視しない
//   ・前年度の実践を否定せず「今年の子どもにとってどうか」で選び直す
//   ・最後は大改革案ではなく「次に一つだけ変えるなら」に着地する
